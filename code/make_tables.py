"""Generate the paper's LaTeX tables from files in results/, so no number is ever typed by hand.

CLAUDE.md rule 1: every number must come from code that actually ran, and every table must record
the script and result file that produced it. This script is that link. It reads whatever results
exist and writes LaTeX into paper/tables/; the table caption names the source file.

Inputs (whichever exist)
  results/baselines_ext_<split>.json   classical baselines + conformal (code/baselines_ext.py)
  results/metrics_<tag>.json           per-condition metrics (code/evaluate.py)

Outputs
  paper/tables/baselines_<split>.tex
  paper/tables/conformal_<split>.tex
  paper/tables/conditions_<split>.tex  (one row per condition, classical and LLM together)

Usage: python make_tables.py --split test
"""
import argparse
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..")
TABLES = os.path.join(ROOT, "paper", "tables")


def read_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def pct(x):
    return "--" if x is None else f"{100 * x:.1f}"


def num(x, digits=3):
    return "--" if x is None else f"{x:.{digits}f}"


def write(name, text):
    os.makedirs(TABLES, exist_ok=True)
    path = os.path.join(TABLES, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", path)


def baselines_table(split, data):
    rows = []
    for method, m in data.get("methods", {}).items():
        if "skipped" in m:
            continue
        rows.append((method.replace("_", r"\_"), m))
    out = [
        f"% Generated by code/make_tables.py from results/baselines_ext_{split}.json",
        r"\begin{table*}[t]\centering", r"\small",
        r"\caption{Classical baselines on the %s split. Source: \texttt{results/baselines\_ext\_%s.json}.}" % (split, split),
        r"\label{tab:baselines-%s}" % split,
        r"\begin{tabular}{lrrrrrr}", r"\toprule",
        r"Method & Acc & Macro-F1 & Top-3 & AURC & Acc@50\% & Acc@80\% \\", r"\midrule",
    ]
    for method, m in rows:
        out.append(" & ".join([
            method, pct(m.get("acc")), pct(m.get("macro_f1")), pct(m.get("top3")),
            num(m.get("AURC_risk")), pct(m.get("selective_acc_cov50")),
            pct(m.get("selective_acc_cov80"))]) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write(f"baselines_{split}.tex", "\n".join(out))


def conformal_table(split, data):
    conf = data.get("conformal")
    if not conf:
        return
    out = [
        f"% Generated by code/make_tables.py from results/baselines_ext_{split}.json",
        r"\begin{table*}[t]\centering",
        r"\caption{Split-conformal prediction sets for TF-IDF+LR on the %s split. Calibration is the last quarter of the training period; the coverage gap is the finite-sample and distribution-shift effect. Source: \texttt{results/baselines\_ext\_%s.json}.}" % (split, split),
        r"\label{tab:conformal-%s}" % split,
        r"\begin{tabular}{lrrrr}", r"\toprule",
        r"$\alpha$ & Target cov. & Empirical cov. & Mean set size & Singleton rate \\", r"\midrule",
    ]
    for key in sorted(conf):
        c = conf[key]
        out.append(" & ".join([key.replace("alpha", r"$\alpha$="),
                               pct(c["target_coverage"]), pct(c["empirical_coverage"]),
                               num(c["mean_set_size"], 2), pct(c["singleton_rate"])]) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write(f"conformal_{split}.tex", "\n".join(out))


# Runs that exist to validate the pipeline or settle a configuration question, not to be reported:
# the three-bug smoke tests and the 100-bug thinking-mode A/B. The full-pool sweep supersedes them,
# and mixing their small n into a results table would be misleading.
PILOT_MARKERS = ("_n3_", "_n6_", "_n12_", "_n100_")


def conditions_table(split):
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "results", "metrics_*.json"))):
        if "mock" in os.path.basename(path):
            continue          # mock runs only test the pipeline; they are never paper results
        r = read_json(path)
        if r.get("split") != split:
            continue          # one table per test split; never mix periods in one comparison
        tag = r.get("tag") or ""
        if "settled" in tag:
            continue          # subset runs are reported separately, never as extra rows here
        if any(marker in tag for marker in PILOT_MARKERS):
            continue          # pilots and the A/B config study; the full sweep supersedes them
        m = r.get("metrics") or {}
        cond = r.get("condition") or os.path.basename(path)
        model = r.get("model") or ""
        seed = r.get("seed")
        if not m:
            continue
        rows.append((f"{cond}", model, seed, m))
    if not rows:
        print("no metrics_*.json yet, skipping the conditions table")
        return
    out = [
        r"% Generated by code/make_tables.py from results/metrics_*.json (code/evaluate.py)",
        r"\begin{table*}[t]\centering",
        r"\caption{Every condition, scored by one evaluator so the risk-coverage curves are directly comparable. Source: \texttt{results/metrics\_*.json}.}",
        r"\label{tab:conditions-%s}" % split,
        r"\begin{tabular}{llrrrrrrrrr}", r"\toprule",
        r"Condition & Model & Seed & $n$ & Acc & Macro-F1 & Top-3 & AURC & Acc@80\% & Abstain & \$/bug \\",
        r"\midrule",
    ]
    for cond, model, seed, m in rows:
        out.append(" & ".join([
            cond.replace("_", r"\_"), model.replace("_", r"\_"), str(seed if seed is not None else "--"),
            f"{m.get('n', 0):,}".replace(",", r"{,}"),
            pct(m.get("acc_all")), pct(m.get("macro_f1")), pct(m.get("top3")),
            num(m.get("AURC_risk")), pct(m.get("selective_acc_cov80")),
            pct((m.get("explicit_abstain") or {}).get("abstain_rate")),
            num(m.get("cost_usd_per_bug"), 5)]) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write(f"conditions_{split}.tex", "\n".join(out))


def ambiguity_table(split, settled=False):
    """The paper's central table: accuracy and abstention split by ownership-ambiguity category.

    The point of the table is the sign of the last two columns against the first three: a model is
    less accurate on `specific_reassign` than on `never_changed`, yet its confidence-based
    abstention rate on that group is no higher, which is exactly the failure the paper studies.
    """
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "results", "metrics_*.json"))):
        if "mock" in os.path.basename(path):
            continue
        r = read_json(path)
        if r.get("split") != split:
            continue
        tag = r.get("tag") or ""
        if ("settled" in tag) != settled:
            continue          # subset runs get their own table; never mix them into the main one
        if any(marker in tag for marker in PILOT_MARKERS):
            continue          # pilots and the A/B config study, not reported results
        cats = (r.get("metrics") or {}).get("by_ambiguity_category") or {}
        if not cats:
            continue
        rows.append((r.get("condition") or os.path.basename(path), r.get("model"), cats))
    if not rows:
        print("no metrics with an ambiguity breakdown yet, skipping that table")
        return
    out = [
        f"% Generated by code/make_tables.py from results/metrics_*.json (code/evaluate.py)",
        r"\begin{table*}[t]\centering",
        (r"\caption{Accuracy and confidence-based abstention by ownership-ambiguity category on %s. "
         r"Every classical method is less accurate on \texttt{specific\_reassign} than on "
         r"\texttt{never\_changed} and abstains no more often there (lift below 1), so its "
         r"confidence does not track the ambiguity. The agent abstains more often on it (lift 1.21) "
         r"and is 14.4 points more accurate there than the best classical model. Categories come "
         r"from \texttt{code/label\_cleaning.py}.}"
         % ("the settled subset, i.e.\ bugs filed at least 90 days before the freeze" if settled
            else "the full " + split + " split")),
        r"\label{tab:ambiguity-%s%s}" % (split, "-settled" if settled else ""),
        r"\begin{tabular}{llrrrrrrrr}", r"\toprule",
        r"Condition & Model & Acc never & Acc specific & Gap & Abst.\ specific & Abst.\ never & Lift & Pred=init & Err=init \\",
        r"\midrule",
    ]
    for cond, model, cats in rows:
        never = cats.get("never_changed") or {}
        spec = cats.get("specific_reassign") or {}
        a_n, a_s = never.get("acc"), spec.get("acc")
        gap = "--" if (a_n is None or a_s is None) else f"{100 * (a_n - a_s):.1f}"
        out.append(" & ".join([
            str(cond).replace("_", r"\_"), str(model).replace("_", r"\_"), pct(a_n), pct(a_s), gap,
            pct(spec.get("abstain_rate_by_confidence_at_cov80")),
            pct(never.get("abstain_rate_by_confidence_at_cov80")),
            ("--" if spec.get("abstain_lift_at_cov80") is None
             else f"{spec['abstain_lift_at_cov80']:.2f}"),
            pct(spec.get("pred_eq_initial_team_rate")),
            pct(spec.get("error_is_initial_team_rate"))]) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write(f"ambiguity_{split}{'_settled' if settled else ''}.tex", "\n".join(out))


def categories_table():
    """Ownership-ambiguity category counts per split (code/label_cleaning.py)."""
    path = os.path.join(ROOT, "results", "label_categories.json")
    if not os.path.exists(path):
        print("missing results/label_categories.json, skipping the category table")
        return
    by = read_json(path).get("by_split") or {}
    splits = [s for s in ("train", "test", "test2026") if s in by]
    categories = ["never_changed", "inbox_triage", "specific_reassign", "bot_only"]

    def thousands(value):
        return f"{value:,}".replace(",", r"{,}")

    out = [
        r"% Generated by code/make_tables.py from results/label_categories.json",
        r"\begin{table}[t]\centering", r"\small",
        r"\caption{Ownership-ambiguity categories per split. Categories come from the component and product changes recorded in each bug's history; \texttt{bot\_only} is excluded from the analysis because an automation move carries no evidence of human disagreement. Source: \texttt{results/label\_categories.json} (\texttt{code/label\_cleaning.py}).}",
        r"\label{tab:categories}",
        r"\begin{tabular}{l" + "r" * len(splits) + "}", r"\toprule",
        "Category & " + " & ".join(splits) + r" \\", r"\midrule",
    ]
    for cat in categories:
        out.append(cat.replace("_", r"\_") + " & "
                   + " & ".join(thousands(by.get(s, {}).get(cat, 0)) for s in splits) + r" \\")
    out.append(r"\midrule")
    out.append("total & " + " & ".join(thousands(by.get(s, {}).get("total", 0))
                                       for s in splits) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write("categories.tex", "\n".join(out))


def period_table(splits=("test", "test2026")):
    """The same ownership-ambiguity reversal on two independent test periods.

    The paper's claim is that overall accuracy hides the subgroup where ownership actually moved.
    If that held only on the 2026 period it would look like an artifact of one data slice, so the
    identical numbers are reported for the 2024 period, whose bugs were filed two years earlier.
    Every condition here runs locally, so this costs nothing and needs no LLM calls.
    """
    conditions = {}
    for split in splits:
        for path in sorted(glob.glob(os.path.join(ROOT, "results", "metrics_*.json"))):
            base = os.path.basename(path)
            if ("mock" in base or "settled" in base
                    or any(marker in base for marker in PILOT_MARKERS)):
                continue
            d = read_json(path)
            if d.get("split") != split:
                continue
            m = d.get("metrics") or {}
            if "by_ambiguity_category" not in m or m.get("model") not in (None, "", "classical"):
                continue          # the LLM conditions only exist for the 2026 period
            conditions.setdefault(d.get("condition"), {})[split] = m
    shared = sorted(c for c, per in conditions.items() if all(s in per for s in splits))
    if not shared:
        print("period_table: no condition is present on both splits; skipped")
        return

    def cell(m, key):
        v = m.get(key)
        return "--" if v is None else "%.1f" % (100 * v)

    def category(m, name, key):
        return cell((m.get("by_ambiguity_category") or {}).get(name) or {}, key)

    lines = [
        "% Generated by code/make_tables.py from results/metrics_*.json.",
        r"\begin{table*}[t]\centering", r"\small",
        r"\caption{The reversal on two independent test periods. ``Never'' and ``Moved'' are the "
        r"accuracy on bugs whose component was never reassigned and on bugs whose component was "
        r"moved away from a concrete one. Both periods come from the same tracker two years apart "
        r"and the pattern is identical: the reporter baseline wins overall, is perfect where "
        r"ownership never moved, and collapses where it did, falling below TF-IDF with logistic "
        r"regression. Source: \texttt{results/metrics\_*.json}, "
        r"\texttt{results/baselines\_ext\_*.json}.}",
        r"\label{tab:periods}",
        r"\begin{tabular}{llrrrrr}", r"\toprule",
        r"Period & Condition & $n$ & Acc & Never & Moved & $n$ moved \\",
        r"\midrule",
    ]
    for i, split in enumerate(splits):
        label = "2024" if split == "test" else "2026"
        for cond in shared:
            m = conditions[cond][split]
            sp = (m.get("by_ambiguity_category") or {}).get("specific_reassign") or {}
            lines.append(" & ".join([
                label if cond == shared[0] else "",
                cond.replace("_", r"\_"),
                f"{m.get('n', 0):,}".replace(",", r"{,}"),
                cell(m, "acc_all"),
                category(m, "never_changed", "acc"),
                category(m, "specific_reassign", "acc"),
                f"{sp.get('n', 0):,}".replace(",", r"{,}"),
            ]) + r" \\")
        if i + 1 < len(splits):
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write("periods.tex", "\n".join(lines))
    print(f"wrote periods.tex ({len(shared)} conditions x {len(splits)} periods)")


def cost_latency_table(split="test2026"):
    """Cost and latency per condition -- what a deployment would actually pay, per bug.

    These belong beside the accuracy numbers rather than in prose, because they cut against the
    headline result: the agent is the most accurate method on the hard subgroup and also the most
    expensive by two orders of magnitude. Stating both in one table makes the trade-off explicit
    instead of leaving the reader to infer it.
    """
    order = {"agent": 0, "zeroshot": 1, "rag": 2}
    rows, seen = [], set()
    for path in sorted(glob.glob(os.path.join(ROOT, "results", "metrics_*.json"))):
        base = os.path.basename(path)
        if "mock" in base or any(m in base for m in PILOT_MARKERS) or "settled" in base:
            continue
        d = read_json(path)
        if d.get("split") != split:
            continue
        m = d.get("metrics") or {}
        label = d.get("condition") or base
        if label in seen:
            continue
        seen.add(label)
        model = d.get("model") or ""
        shown = label if not model or model == "classical" else f"{label} ({model})"
        rows.append((order.get(label, 9), shown, m))
    rows.sort(key=lambda r: (r[0], r[1]))

    def g(m, key, fmt="%.4f"):
        v = m.get(key)
        if v is None:
            return "--"
        try:
            return fmt % float(v)
        except (TypeError, ValueError):
            return "--"

    lines = [
        f"% Generated by code/make_tables.py from results/metrics_*.json ({split}).",
        r"\begin{table*}[t]\centering", r"\small",
        r"\caption{Cost and latency per bug on the %s split. Costs are the recorded API spend at "
        r"off-peak list price; the classical methods run locally and cost nothing. ``in'' and "
        r"``out'' are mean prompt and completion tokens, and ``calls'' the mean number of tool "
        r"calls per bug. A dash means the quantity does not apply. Source: "
        r"\texttt{results/metrics\_*.json}; the billed total, including peak-hour calls, is audited "
        r"by \texttt{code/spend\_report.py} into \texttt{results/spend\_report.json}.}" % split,
        r"\label{tab:cost-%s}" % split,
        r"\begin{tabular}{lrrrrrr}", r"\toprule",
        r"Condition & $n$ & \$/bug & in & out & s/bug & calls \\", r"\midrule",
    ]
    for _, label, m in rows:
        lines.append(" & ".join([
            label.replace("_", r"\_"),
            f"{m.get('n', 0):,}".replace(",", r"{,}"),
            g(m, "cost_usd_per_bug"),
            # A local baseline spends no tokens and waits on no API, but printing 0 in those cells
            # invites the reader to average them in. The caption promises a dash for "does not
            # apply", so a dash is what they get.
            *(["--"] * 4 if not m.get("cost_usd_per_bug") else [
                g(m, "prompt_tokens_mean", "%.0f"),
                g(m, "completion_tokens_mean", "%.0f"),
                g(m, "latency_s_mean", "%.2f"),
                g(m, "n_tool_calls_mean", "%.2f")]),
        ]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write(f"cost_latency_{split}.tex", "\n".join(lines))
    print(f"wrote cost_latency_{split}.tex ({len(rows)} conditions)")


def zh_markdown_tables(split="test2026"):
    """The same tables the English paper uses, emitted as markdown for the Chinese version.

    The Chinese paper is markdown, so it cannot \\input a LaTeX table the way main.tex does. Its
    tables were copied by hand once and then silently froze: an audit against the English version
    found forty lines still quoting the first day's numbers, which the author reads. Emitting them
    from the same results/ files as everything else removes that whole class of divergence.

    Writes paper/tables/zh_tables.json, which paper/build.py substitutes into {{TABLE:key}} markers.
    """
    llm_order = {"agent": 0, "zeroshot": 1, "rag": 2}
    rows, seen = [], set()
    for path in sorted(glob.glob(os.path.join(ROOT, "results", "metrics_*.json"))):
        base = os.path.basename(path)
        if "mock" in base or "settled" in base or any(m in base for m in PILOT_MARKERS):
            continue
        d = read_json(path)
        if d.get("split") != split or d.get("condition") in seen:
            continue
        seen.add(d.get("condition"))
        rows.append(d)
    # LLM conditions first in a fixed order, then the classical ones by accuracy
    rows.sort(key=lambda d: (llm_order.get(d.get("condition"), 9),
                             -((d.get("metrics") or {}).get("acc_all") or 0.0)))

    def pct1(v):
        return "--" if v is None else "%.1f" % (100 * v)

    def num3(v):
        return "--" if v is None else "%.3f" % v

    def cat(m, name):
        return (m.get("by_ambiguity_category") or {}).get(name) or {}

    def bold(text, on):
        return f"**{text}**" if on else text

    conditions = ["| 条件 | n | Acc | 宏F1 | Top-3 | AURC | 80%覆盖Acc | $/bug |",
                  "|---|---|---|---|---|---|---|---|"]
    ambiguity = ["| 条件 | 无歧义组 Acc | 歧义组 Acc | 差距 | 歧义组拒答 | 无歧义组拒答 "
                 "| 拒答 lift | 错在「最初选择」 |",
                 "|---|---|---|---|---|---|---|---|"]
    for d in rows:
        cond, m = d.get("condition"), d.get("metrics") or {}
        is_llm = cond in llm_order
        sp, nv = cat(m, "specific_reassign"), cat(m, "never_changed")
        usd = m.get("cost_usd_per_bug")
        conditions.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            bold(cond, is_llm),
            f"{m.get('n', 0):,}",
            bold(pct1(m.get("acc_all")), is_llm),
            pct1(m.get("macro_f1")),
            bold(pct1(m.get("top3")), is_llm),
            bold(num3(m.get("AURC_risk")), is_llm),
            bold(pct1(m.get("selective_acc_cov80")), is_llm),
            ("%.5f" % usd) if usd else "—"))
        gap = (None if (sp.get("acc") is None or nv.get("acc") is None)
               else 100 * (nv["acc"] - sp["acc"]))
        ambiguity.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            bold(cond, is_llm),
            pct1(nv.get("acc")),
            bold(pct1(sp.get("acc")), is_llm),
            bold("%.1f" % gap, is_llm) if gap is not None else "--",
            bold(pct1(sp.get("abstain_rate_by_confidence_at_cov80")), is_llm),
            pct1(nv.get("abstain_rate_by_confidence_at_cov80")),
            bold("%.2f" % sp["abstain_lift_at_cov80"], is_llm)
            if sp.get("abstain_lift_at_cov80") is not None else "--",
            pct1(sp.get("error_is_initial_team_rate"))))

    periods = ["| 测试期 | 条件 | n | Acc | 从未改派 | 被改派 | 改派 n |",
               "|---|---|---|---|---|---|---|"]
    for split_name, label in (("test", "2024"), ("test2026", "2026")):
        for path in sorted(glob.glob(os.path.join(ROOT, "results", "metrics_*.json"))):
            base = os.path.basename(path)
            if ("mock" in base or "settled" in base or "initial_team" == ""
                    or any(m in base for m in PILOT_MARKERS)):
                continue
            d = read_json(path)
            if (d.get("split") != split_name or "by_ambiguity_category" not in (d.get("metrics") or {})
                    or (d.get("model") or "classical") != "classical"):
                continue
            m = d["metrics"]
            sp = cat(m, "specific_reassign")
            periods.append("| %s | %s | %s | %s | %s | %s | %s |" % (
                label, d.get("condition"), f"{m.get('n', 0):,}", pct1(m.get("acc_all")),
                pct1(cat(m, "never_changed").get("acc")), pct1(sp.get("acc")), sp.get("n", 0)))

    tables = {"conditions": "\n".join(conditions),
              "ambiguity": "\n".join(ambiguity),
              "periods": "\n".join(periods)}
    with open(os.path.join(TABLES, "zh_tables.json"), "w", encoding="utf-8") as fh:
        json.dump(tables, fh, ensure_ascii=False, indent=1)
    print(f"wrote zh_tables.json ({len(tables)} tables: {', '.join(sorted(tables))})")


def numbers_macros(split="test2026"):
    """Emit every figure the prose quotes as a LaTeX macro.

    The budgeted sweep adds bugs day by day, so these figures move. Hard-coding them in the prose
    means the text silently disagrees with the tables it cites after every run. Defining them here
    and regenerating them with the tables keeps prose and tables equal by construction, which is
    what the workspace rule about traceable numbers actually requires in practice.
    """
    def load(cond, tag_contains="n6347"):
        for path in sorted(glob.glob(os.path.join(ROOT, "results", "metrics_*.json"))):
            base = os.path.basename(path)
            if "mock" in base or tag_contains not in base:
                continue
            d = read_json(path)
            if d.get("split") != split or d.get("condition") != cond:
                continue
            if "settled" in (d.get("tag") or ""):
                continue
            return d.get("metrics") or {}
        return {}

    def cat(m, name):
        return (m.get("by_ambiguity_category") or {}).get(name) or {}

    def val(m, key, catname=None, scale=1.0):
        """A number, or None, so a derived figure never has to rely on short-circuit tricks."""
        if catname:
            m = cat(m, catname)
        v = m.get(key)
        return None if v is None else float(v) * scale

    def f1(v):
        return "--" if v is None else "%.1f" % v

    def f3(v):
        return "--" if v is None else "%.3f" % v

    def f2(v):
        return "--" if v is None else "%.2f" % v

    def thou(v):
        return f"{v:,}".replace(",", r"{,}")

    def diff(a, b):
        return "--" if a is None or b is None else "%.1f" % (a - b)

